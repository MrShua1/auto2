  const episodeCommand = fs.readFileSync(path.join(skillRoot, 'references', 'episode-command.md'), 'utf8');
  const tscModule = fs.readFileSync(path.join(skillRoot, 'modules', 'tsc', 'MODULE.md'), 'utf8');
  const combined = [skill, productionRules, qualityGates, episodeCommand, tscModule].join('\n');
