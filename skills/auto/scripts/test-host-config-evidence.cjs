const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { summarize } = require('./host-config-evidence.cjs');
const target = path.resolve('Fixture User With Spaces');
const entry = path.join(target, 'plugins/fast-image.ts');
assert.equal(summarize({ plugin: [pathToFileURL(entry).href] }, target).fastImageDiscovered, true);
assert.equal(summarize({ plugin: [[entry, {}]] }, target).fastImageDiscovered, true);
const other = summarize({ plugin: [path.resolve('Other User/plugins/fast-image.ts')] }, target);
assert.equal(other.fastImageDiscovered, false);
assert.equal(other.otherFastImageEntryDiscovered, true);
assert.equal(summarize({ plugin: ['./plugins/fast-image.ts', 'file:%invalid'] }, target).fastImageDiscovered, null);
assert.equal(summarize({ plugin: ['./plugins/fast-image.ts'] }, target, { configBase: target }).fastImageDiscovered, true);
assert.equal(summarize({ plugin: [['./plugins/fast-image.ts', {}]] }, target, { configBase: path.resolve('Other User') }).fastImageDiscovered, false);
assert.equal(summarize({ plugin: ['../plugins/fast-image.ts'] }, target, { configBase: path.join(target, 'nested') }).fastImageDiscovered, true);
assert.equal(summarize({ plugin: ['opencode-plugin-package'] }, target).fastImageDiscovered, false);
assert.equal(summarize({ plugin: [entry, './unknown.ts'] }, target).fastImageDiscovered, true);
const denied = summarize({ permission: 'deny', agent: { build: { tools: { direct_image_run: false } } } }, target);
assert.equal(denied.permission, 'deny');
assert.equal(denied.agentToolDisabled, true);
const summary = summarize({ provider: { 'direct-image': { apiKey: 'TEST_SECRET_MUST_NOT_LEAK' } } }, target);
assert.equal(summary.directImageProviderVisible, true);
assert.equal(JSON.stringify(summary).includes('TEST_SECRET_MUST_NOT_LEAK'), false);
console.log('Host configuration evidence: absolute, relative, unknown-base, tuple, permission and redaction checks passed');
